#!/usr/bin/env node
/**
 * Regenerates deep-recursive-object.slow.ts and .fixed.ts.
 *
 * A chain of NODE_COUNT distinct, non-uniform levels (Node0 -> Node1 -> ...),
 * each carrying FIELD_COUNT sibling fields so the recursion has real
 * per-level weight, not just per-level count. Widening FIELD_COUNT (rather
 * than lengthening the chain) is what pushes Check time far enough apart
 * to read clearly above run-to-run noise, without approaching the
 * "excessive stack depth" (TS2321) limit that a longer chain would hit.
 *
 * Usage: node generate-deep-recursive-object.mjs [fieldCount] [nodeCount]
 */

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const DIR = dirname(fileURLToPath(import.meta.url));
const FIELD_COUNT = Number(process.argv[2]) || 200;
const NODE_COUNT = Number(process.argv[3]) || 66;

function siblingFields() {
  const fields = [];
  for (let f = 0; f < FIELD_COUNT; f++) {
    fields.push(
      `field${f}: { value: string; count: number; flag: boolean; created: Date; pattern: RegExp }`,
    );
  }
  return fields.join("; ") + ";";
}

const FIELDS = siblingFields();

function nodeType(i) {
  const next = i === NODE_COUNT - 1 ? "null" : `Node${i + 1}`;
  return `type Node${i} = { id: string; label: string; count: number; active: boolean; tags: string[]; metadata: { created: Date; updated: Date }; ${FIELDS} next: ${next} };`;
}

function nodeLiteral(i) {
  const fields = [];
  for (let f = 0; f < FIELD_COUNT; f++) {
    fields.push(
      `field${f}: { value: "x", count: 1, flag: true, created: new Date(), pattern: /x/ }`,
    );
  }
  const next = i === 0 ? "n1" : i === NODE_COUNT - 1 ? "null" : `n${i + 1}`;
  return `const n${i} = { id: "n${i}", label: "node-${i}", count: ${i}, active: true, tags: ["a", "b"], metadata: { created: new Date(), updated: new Date() }, ${fields.join(", ")}, next: ${next} };`;
}

function nodeTypes() {
  const lines = [];
  for (let i = NODE_COUNT - 1; i >= 0; i--) lines.push(nodeType(i));
  return lines.join("\n");
}

function nodeLiterals() {
  const lines = [];
  for (let i = NODE_COUNT - 1; i >= 0; i--) lines.push(nodeLiteral(i));
  return lines.join("\n");
}

function createSlowFile() {
  return `/**
 * SLOW: Deep recursive object transformation (unbounded)
 *
 * Recursive mapped types (DeepPartial, DeepReadonly, schema transformers)
 * repeatedly drive transformations at each nesting level with no terminal
 * case and no depth limit.
 *
 * \`Node0\` is a chain of ${NODE_COUNT} distinct, non-uniform levels (Node0 ->
 * Node1 -> ... -> Node${NODE_COUNT - 1}). Each level is a genuinely different
 * named type, not a single self-referential type, so the checker cannot use
 * its usual recursive-type shortcut (assuming the relation holds and
 * checking one level) - it has to walk the entire chain. That walk is
 * forced by assigning the matching \`n0\` literal to \`Result\`, which
 * requires a full structural comparison against the unbounded
 * \`DeepReadonly<Node0>\`.
 *
 * Each level also carries ${FIELD_COUNT} additional sibling fields
 * (\`field0\`..\`field${FIELD_COUNT - 1}\`, each an inline
 * \`{ value, count, flag, created, pattern }\` object) beyond the core
 * \`id\`/\`label\`/\`metadata\`/\`next\` shape. TypeScript's "excessive stack
 * depth" limit for this kind of structural recursion kicks in well before
 * ${NODE_COUNT * 3} levels, so depth alone can't push the cost into
 * measurable wall-clock time - widening every level instead multiplies the
 * per-level cost that recursion pays ${NODE_COUNT} times here but only 5
 * times in the fixed version, which is what finally makes Check
 * time/Total time move.
 *
 * Generated by generate-deep-recursive-object.mjs ${FIELD_COUNT} ${NODE_COUNT}
 */

type DeepReadonly<T> =
  T extends (...args: any[]) => any
    ? T
    : T extends object
      ? { readonly [K in keyof T]: DeepReadonly<T[K]> }
      : T;

${nodeTypes()}

type Result = DeepReadonly<Node0>; // walks all ${NODE_COUNT} levels, each with ${FIELD_COUNT} extra sibling fields

${nodeLiterals()}

const raw: Node0 = n0;
const result: Result = raw;

export {};
`;
}

function createFixedFile() {
  return `/**
 * FIXED: Add explicit terminal cases and a depth limit
 *
 * - Stop at known primitives (string, number, Date, RegExp, etc.)
 * - Stop at a bounded depth (0–5)
 * - Handle arrays and objects explicitly
 *
 * Same ${NODE_COUNT}-level \`Node0..Node${NODE_COUNT - 1}\` chain, the same
 * ${FIELD_COUNT} extra sibling fields per level, and the same \`n0\` literal
 * as the slow version, forced through the same \`Result\` assignment - but
 * because \`DeepReadonly\` stops recursing once \`Depth\` reaches 0, only the
 * first 5 levels (and their ${FIELD_COUNT} sibling fields) are ever
 * transformed. The remaining ${NODE_COUNT - 5} levels are returned as-is,
 * so the comparison is far cheaper.
 *
 * Generated by generate-deep-recursive-object.mjs ${FIELD_COUNT} ${NODE_COUNT}
 */

type Primitive = string | number | boolean | bigint | symbol | null | undefined;
type PreviousDepth = [never, 0, 1, 2, 3, 4, 5];
type DeepReadonly<T, Depth extends number = 5> =
  Depth extends 0 ? T :
  T extends Primitive | Date | RegExp ? T :
  T extends readonly (infer Item)[]
    ? ReadonlyArray<DeepReadonly<Item, PreviousDepth[Depth]>>
    : T extends object
      ? { readonly [K in keyof T]: DeepReadonly<T[K], PreviousDepth[Depth]> }
      : T;

${nodeTypes()}

type Result = DeepReadonly<Node0>; // only Node0..Node4 (Depth = 5) are transformed

${nodeLiterals()}

const raw: Node0 = n0;
const result: Result = raw;

export {};
`;
}

writeFileSync(join(DIR, "deep-recursive-object.slow.ts"), createSlowFile());
writeFileSync(join(DIR, "deep-recursive-object.fixed.ts"), createFixedFile());

console.log(
  `Generated slow and fixed files with ${NODE_COUNT} levels x ${FIELD_COUNT} fields.`,
);
