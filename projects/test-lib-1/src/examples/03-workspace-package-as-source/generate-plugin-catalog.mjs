#!/usr/bin/env node
/**
 * Regenerates package-lib/src/catalog.ts.
 *
 * A handful of hand-written plugin settings types is too little real checker
 * work to make the source-vs-declaration gap show up in wall-clock time (see
 * the tiny baseline this replaced: ~0.05s Check time either way). This
 * generates a realistic plugin catalog instead: N distinct, deeply-nested
 * plugin settings shapes (retry/timeout/cache/auth/logging/limits), pushed
 * through DeepMerge/DeepRequired/Paths exactly the way normalize.ts and
 * schema.ts already use those utilities - the library just has more real
 * surface for them to work over.
 *
 * Usage: node generate-plugin-catalog.mjs [count]
 */

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const DIR = dirname(fileURLToPath(import.meta.url));
const PLUGIN_COUNT = Number(process.argv[2]) || 40;

function settingsInterface(i) {
  return `export interface Plugin${i}Settings {
  kind: "plugin-${i}";
  name: string;
  enabled: boolean;
  priority: number;
  retry: { attempts: number; backoffMs: number; maxBackoffMs: number };
  timeout: { connectMs: number; readMs: number; totalMs: number };
  cache: { ttlSeconds: number; maxEntries: number; staleWhileRevalidate: boolean };
  auth: { mode: "none" | "apiKey" | "oauth2"; headerName: string; scopes: string[] };
  logging: { level: "debug" | "info" | "warn" | "error"; redactFields: string[] };
  limits: { maxConcurrent: number; maxQueueSize: number };
  metadata: Record<string, string>;
}`;
}

function defaultsLiteral(i) {
  return `  "plugin-${i}": {
    kind: "plugin-${i}",
    name: "plugin-${i}",
    enabled: true,
    priority: ${i},
    retry: { attempts: 3, backoffMs: 100, maxBackoffMs: 2000 },
    timeout: { connectMs: 1000, readMs: 5000, totalMs: 10000 },
    cache: { ttlSeconds: 60, maxEntries: 500, staleWhileRevalidate: true },
    auth: { mode: "apiKey", headerName: "x-api-key", scopes: ["read"] },
    logging: { level: "info", redactFields: ["authorization"] },
    limits: { maxConcurrent: 10, maxQueueSize: 100 },
    metadata: {},
  }`;
}

function generate() {
  const header = `/**
 * Plugin catalog: one deeply-nested settings shape per supported plugin
 * kind. Each of the ${PLUGIN_COUNT} interfaces below is structurally similar
 * but a distinct named type, so DeepMerge/DeepRequired/Paths (see ./merge,
 * ./types, ./paths) can't shortcut the recursion across them - every branch
 * gets its own full structural walk, the same way ./normalize.ts already
 * forces one for RawConfig via \`DEFAULTS: DeepRequired<RawConfig>\`.
 *
 * Generated by generate-plugin-catalog.mjs ${PLUGIN_COUNT}
 */
`;

  const body = [header];

  for (let i = 1; i <= PLUGIN_COUNT; i++) {
    body.push(settingsInterface(i));
    body.push("");
  }

  body.push(
    `export type PluginSettings =\n  ${Array.from({ length: PLUGIN_COUNT }, (_, i) => `Plugin${i + 1}Settings`).join(" |\n  ")};`,
  );
  body.push("");

  body.push(
    `export type PluginCatalog = {\n${Array.from({ length: PLUGIN_COUNT }, (_, i) => `  "plugin-${i + 1}": Plugin${i + 1}Settings;`).join("\n")}\n};`,
  );
  body.push("");

  body.push(
    `export const catalogDefaults: PluginCatalog = {\n${Array.from({ length: PLUGIN_COUNT }, (_, i) => defaultsLiteral(i + 1)).join(",\n")},\n};`,
  );
  body.push("");

  return body.join("\n");
}

writeFileSync(join(DIR, "package-lib/src/catalog.ts"), generate());

console.log(`Generated catalog.ts with ${PLUGIN_COUNT} plugin settings types.`);
