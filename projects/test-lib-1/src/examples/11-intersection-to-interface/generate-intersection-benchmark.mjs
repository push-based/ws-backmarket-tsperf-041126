#!/usr/bin/env node
/**
 * Regenerates intersection-to-interface.slow.ts and .fixed.ts.
 *
 * Ten aliases is too little measurable checker work on a modern machine.
 * This generates a realistic SaaS-shaped model instead: a 16-trait entity
 * base reused across N domain entities, each pushed through the mapped
 * types, generics, and assignments that a real app's entities actually
 * flow through (repositories, events, API responses, patches, snapshots,
 * validators, base<->derived assignability).
 *
 * Usage: node generate-intersection-benchmark.mjs [count]
 */

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const DIR = dirname(fileURLToPath(import.meta.url));
const ENTITY_COUNT = Number(process.argv[2]) || 250;

const traits = `
type EntityStatus = "draft" | "active" | "suspended" | "archived";
type Permission = "read" | "write" | "delete" | "admin";

interface WithIdentity {
  id: string;
  externalId: string | null;
}

interface WithTimestamps {
  createdAt: Date;
  updatedAt: Date;
  deletedAt: Date | null;
}

interface WithOwnership {
  ownerId: string;
  organizationId: string;
  teamId: string | null;
}

interface WithStatus {
  status: EntityStatus;
  statusChangedAt: Date;
  statusReason: string | null;
}

interface WithVersion {
  version: number;
  revision: number;
  etag: string;
}

interface WithAudit {
  createdBy: string;
  updatedBy: string;
  approvedBy: string | null;
}

interface WithTags {
  tags: readonly string[];
  labels: Readonly<Record<string, string>>;
}

interface WithMetadata {
  metadata: Readonly<Record<string, unknown>>;
  customFields: Readonly<Record<string, string | number | boolean>>;
}

interface WithPermissions {
  permissions: readonly Permission[];
  isPublic: boolean;
}

interface WithTenant {
  tenantId: string;
  tenantRegion: "eu" | "us" | "apac";
}

interface WithLocalization {
  locale: string;
  timezone: string;
}

interface WithLifecycle {
  publishedAt: Date | null;
  expiresAt: Date | null;
  archivedAt: Date | null;
}

interface WithSearch {
  searchText: string;
  searchKeywords: readonly string[];
}

interface WithSource {
  sourceSystem: string;
  sourceReference: string | null;
  importedAt: Date | null;
}

interface WithSecurity {
  classification: "public" | "internal" | "confidential";
  encryptionKeyId: string | null;
}

interface WithWorkflow {
  workflowId: string | null;
  workflowStep: number;
  workflowState: "pending" | "running" | "complete" | "failed";
}
`;

const sharedUtilities = `
type ApiResponse<T> = {
  data: T;
  requestId: string;
  receivedAt: Date;
};

type DomainEvent<T> = {
  eventId: string;
  eventType: \`\${string}.created\` | \`\${string}.updated\`;
  aggregateId: string;
  payload: T;
  occurredAt: Date;
};

type EntityPatch<T> = {
  [K in keyof T]?: T[K];
};

type EntitySnapshot<T> = {
  readonly [K in keyof T]: T[K];
};

type EntityValidator<T> = {
  [K in keyof T]-?: (value: T[K]) => boolean;
};

interface Repository<T extends { id: string }> {
  findById(id: string): Promise<T | null>;
  findMany(ids: readonly string[]): Promise<readonly T[]>;
  create(value: T): Promise<T>;
  update(id: string, patch: EntityPatch<T>): Promise<T>;
  saveMany(values: readonly T[]): Promise<readonly T[]>;
}

declare function acceptEntity<T extends {
  id: string;
  ownerId: string;
  organizationId: string;
  status: EntityStatus;
  version: number;
  metadata: Readonly<Record<string, unknown>>;
}>(entity: T): T;
`;

const traitNames = [
  "WithIdentity",
  "WithTimestamps",
  "WithOwnership",
  "WithStatus",
  "WithVersion",
  "WithAudit",
  "WithTags",
  "WithMetadata",
  "WithPermissions",
  "WithTenant",
  "WithLocalization",
  "WithLifecycle",
  "WithSearch",
  "WithSource",
  "WithSecurity",
  "WithWorkflow",
];

function entityFields(index) {
  return `
  entityKind: "entity-${index}";
  name: string;
  description: string;
  sequence: ${index};
  attributes: {
    category: string;
    priority: "low" | "normal" | "high";
    enabled: boolean;
  };
`;
}

function createSlowFile() {
  const lines = [
    `/**
 * SLOW: Deep intersection of mixins, re-flattened at every usage
 *
 * \`EntityBase\` is a 16-way intersection. Every domain entity below
 * intersects it again with its own fields, so the checker re-flattens
 * the same 16 mixins into a fresh anonymous object type at each of the
 * ${ENTITY_COUNT} usage sites - and each of those anonymous types is then
 * pushed through mapped types (patch/snapshot/validator), a generic
 * repository, and base<->derived assignability checks.
 *
 * Generated by generate-intersection-benchmark.mjs ${ENTITY_COUNT}
 */`,
    traits,
    sharedUtilities,
    `
type EntityBase =
  ${traitNames.join(" &\n  ")};
`,
  ];

  for (let i = 1; i <= ENTITY_COUNT; i++) {
    lines.push(`
type Entity${i} = EntityBase & {
${entityFields(i)}
};

type Entity${i}Response = ApiResponse<Entity${i}>;
type Entity${i}Event = DomainEvent<Entity${i}>;
type Entity${i}Patch = EntityPatch<Entity${i}>;
type Entity${i}Snapshot = EntitySnapshot<Entity${i}>;
type Entity${i}Validator = EntityValidator<Entity${i}>;

declare const entity${i}: Entity${i};
declare const repository${i}: Repository<Entity${i}>;

const accepted${i} = acceptEntity(entity${i});
const assign${i}a: EntityBase = entity${i};
const assign${i}b: Entity${i} = accepted${i};
`);
  }

  lines.push(`
export type EveryEntity =
  ${Array.from({ length: ENTITY_COUNT }, (_, i) => `Entity${i + 1}`).join(" |\n  ")};

export type EveryResponse =
  ${Array.from({ length: ENTITY_COUNT }, (_, i) => `Entity${i + 1}Response`).join(" |\n  ")};

export {};
`);

  return lines.join("\n");
}

function createFixedFile() {
  const lines = [
    `/**
 * FIXED: Interface extends, flattened once and reused by name
 *
 * \`EntityBase\` is declared once via \`extends\` - its member list is built
 * a single time and cached under that name. Every domain interface below
 * extends \`EntityBase\` by reference instead of re-flattening its 16
 * mixins, and the ${ENTITY_COUNT} usage sites push the same named
 * interfaces through mapped types, a generic repository, and
 * base<->derived assignability checks.
 *
 * Generated by generate-intersection-benchmark.mjs ${ENTITY_COUNT}
 */`,
    traits,
    sharedUtilities,
    `
interface EntityBase extends
  ${traitNames.join(",\n  ")}
{}
`,
  ];

  for (let i = 1; i <= ENTITY_COUNT; i++) {
    lines.push(`
interface Entity${i} extends EntityBase {
${entityFields(i)}
}

type Entity${i}Response = ApiResponse<Entity${i}>;
type Entity${i}Event = DomainEvent<Entity${i}>;
type Entity${i}Patch = EntityPatch<Entity${i}>;
type Entity${i}Snapshot = EntitySnapshot<Entity${i}>;
type Entity${i}Validator = EntityValidator<Entity${i}>;

declare const entity${i}: Entity${i};
declare const repository${i}: Repository<Entity${i}>;

const accepted${i} = acceptEntity(entity${i});
const assign${i}a: EntityBase = entity${i};
const assign${i}b: Entity${i} = accepted${i};
`);
  }

  lines.push(`
export type EveryEntity =
  ${Array.from({ length: ENTITY_COUNT }, (_, i) => `Entity${i + 1}`).join(" |\n  ")};

export type EveryResponse =
  ${Array.from({ length: ENTITY_COUNT }, (_, i) => `Entity${i + 1}Response`).join(" |\n  ")};

export {};
`);

  return lines.join("\n");
}

writeFileSync(join(DIR, "intersection-to-interface.slow.ts"), createSlowFile());
writeFileSync(join(DIR, "intersection-to-interface.fixed.ts"), createFixedFile());

console.log(`Generated slow and fixed benchmarks with ${ENTITY_COUNT} entities.`);
